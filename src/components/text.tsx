import type { ReactNode } from "react";

/**
 * 닫는 따옴표·괄호, 그 앞, 바로 뒤에 붙은 한글(조사)을 한 덩어리로 묶는 자리. 부호가 둘 이어져도 함께 묶는다.
 * - 따옴표나 괄호 안의 말에 빈칸이 없으면 여는 부호부터 묶는다('(SHA-256)는', '(광고)를'). 그 말 안(예: 'SHA-' 뒤)에서도 줄이
 *   바뀌지 않는다. 앞 글자만 묶으면 'SHA-' ⏎ '256)는' 으로 끊겼다.
 * - 빈칸이 있으면 닫는 부호의 앞 글자부터 묶는다('‘판정 경로’에' 의 '로’에').
 * 따옴표는 ’ ” 와 ' " 를 본다(' " 는 여는 따옴표이기도 해서, 여는 따옴표 바로 뒤의 낱말이 묶여도 줄바꿈 말고는 달라지지 않는다).
 */
const JOINED = /((?:[([‘“「『'"][^\s()[\]‘’“”「」『』'"]*|\S)[’”」』)\]'"]+[가-힣]+)/;

/**
 * 사이트가 쓴 글에서 닫는 따옴표·괄호 뒤의 조사가 줄 머리로 떨어지지 않게 한다('‘판정 경로’ ⏎ 에', '(광고) ⏎ 를').
 *
 * Chrome 은 `word-break: keep-all` 이어도 닫는 부호와 그 뒤의 한글 사이를 줄바꿈 자리로 본다. 따옴표(’)는 앞 글자와의 사이도
 * 그렇다. `line-break`·`text-wrap` 으로는 막지 못했다(9번의 첫 검토). 그래서 위의 자리를 줄을 바꾸지 않는 조각(`.nobreak`)으로
 * 감싼다. 글자는 그대로다(골라 복사한 글, 화면 낭독기와 시험이 읽는 글이 같다). 조각은 사이트가 쓴 짧은 말이라(길어야 열 글자
 * 남짓) 좁은 화면에서도 넘치지 않는다. 묶을 자리가 없으면 글을 그대로 돌려준다.
 *
 * 사이트가 쓴 글에만 쓴다. CLI 출력과 팩의 글(조문 원문, 알리는 말, 질문, 고치는 법)에는 쓰지 않는다. 그 글에도 같은 꼴이
 * 있고 너비에 따라 줄이 바뀐다(docs/architecture.md 의 "글꼴·간격·색").
 */
export function keepParticles(text: string): ReactNode {
  const parts = text.split(JOINED);
  if (parts.length === 1) return text;
  // split 에 묶는 괄호가 있어서 홀수 자리가 묶을 조각이다.
  return parts.map((part, i) =>
    i % 2 === 1 ? (
      <span key={i} className="nobreak">
        {part}
      </span>
    ) : (
      part
    ),
  );
}
